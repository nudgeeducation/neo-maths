/* NEO Maths field kit in lessons (GreenPrint v2.4).
   The unit's diagnostic expedition gives one reference tool per lesson. This adds a "Field kit" button to the
   lesson's support row, opening every tool of the unit with this lesson's tool first. Nothing is recorded.
   Data: assets/fieldkits/<unit-id>.js (window.NEO_FIELDKIT), generated by scripts/fieldkits/make_fieldkits.js. */
(function () {
  var CSS = '.neo-fk-back{position:fixed;inset:0;background:rgba(10,16,24,.55);z-index:9995;display:none;align-items:center;justify-content:center;padding:16px}' +
    '.neo-fk-back.show{display:flex}' +
    '.neo-fk-panel{background:#f7f3ea;border-radius:18px;padding:20px 22px;width:min(680px,100%);max-height:calc(100vh - 40px);overflow:auto;font-family:Arial,sans-serif;color:#2f3429;line-height:1.5}' +
    '.neo-fk-panel h2{color:#3f5f45;margin:0 0 4px}.neo-fk-sub{color:#5c6b4f;margin:0 0 10px;font-size:.92em}' +
    '.neo-fk-label{font-weight:700;color:#5c6b4f;margin:14px 0 4px}' +
    '.neo-fk-tool{display:grid;grid-template-columns:64px 1fr;gap:14px;align-items:start;background:#fff;border-radius:12px;padding:12px 14px;margin:8px 0}' +
    '.neo-fk-tool.here{border:3px solid #d8b26e}.neo-fk-tool svg{width:64px;height:64px}' +
    '.neo-fk-tool h3{margin:0 0 2px;color:#3f5f45;font-size:1.05em}.neo-fk-tool p{margin:4px 0}.neo-fk-from{font-size:.85em;color:#5c6b4f}' +
    '.neo-fk-tool table{border-collapse:collapse}.neo-fk-tool td{border:1px solid #d9d2c4;padding:3px 7px;text-align:center}' +
    '.neo-fk-close{padding:9px 14px;border-radius:10px;border:none;background:#365a68;color:#fff;font-weight:700;cursor:pointer;font-size:1em;margin-top:10px}' +
    '@media (max-width:480px){.neo-fk-tool{grid-template-columns:1fr}.neo-fk-tool svg{width:48px;height:48px}}';
  function card(t, here) {
    return '<div class="neo-fk-tool' + (here ? ' here' : '') + '"><div>' + t.icon + '</div><div><h3>' + t.title + '</h3>' +
      '<div class="neo-fk-from">Found in ' + t.room + ' · ' + t.lesson.replace(/^Lesson (\d+) · /, 'Lesson $1: ') + '</div>' + t.body + '</div></div>';
  }
  function open(i) {
    var kit = window.NEO_FIELDKIT, back = document.getElementById('neoFieldKit');
    var here = kit.tools[i], rest = kit.tools.filter(function (t, k) { return k !== i; });
    back.querySelector('.neo-fk-body').innerHTML =
      '<h2 id="neoFkTitle">🎒 Your field kit</h2><p class="neo-fk-sub">The tools from ' + kit.expedition + ', this unit’s expedition. Use them whenever they help. Looking things up in your kit is good practice, and it is never recorded.</p>' +
      (here ? '<div class="neo-fk-label">For this lesson</div>' + card(here, true) : '') +
      '<div class="neo-fk-label">The rest of the kit</div>' + rest.map(function (t) { return card(t, false); }).join('');
    back.classList.add('show');
    var panel = back.querySelector('.neo-fk-panel'); panel.scrollTop = 0; panel.focus();
  }
  function close() { var b = document.getElementById('neoFieldKit'); if (b) b.classList.remove('show'); }
  window.NEOFieldKit = {
    mount: function (lessonIndex) {
      if (!window.NEO_FIELDKIT || document.getElementById('neoFieldKitBtn')) return;
      var st = document.createElement('style'); st.textContent = CSS; document.head.appendChild(st);
      var back = document.createElement('div'); back.id = 'neoFieldKit'; back.className = 'neo-fk-back';
      back.setAttribute('role', 'dialog'); back.setAttribute('aria-modal', 'true'); back.setAttribute('aria-labelledby', 'neoFkTitle');
      back.innerHTML = '<div class="neo-fk-panel" tabindex="-1"><div class="neo-fk-body"></div><button class="neo-fk-close" type="button">Back to the lesson</button></div>';
      document.body.appendChild(back);
      back.querySelector('.neo-fk-close').onclick = close;
      back.addEventListener('click', function (e) { if (e.target === back) close(); });
      document.addEventListener('keydown', function (e) { if (e.key === 'Escape') close(); });
      var btn = document.createElement('button'); btn.id = 'neoFieldKitBtn'; btn.type = 'button'; btn.className = 'guidebtn'; btn.textContent = '🎒 Field kit';
      btn.onclick = function () { open(lessonIndex); };
      var row = document.querySelector('.guides .buttonrow') || document.querySelector('.buttonrow');
      if (row) { var rc = row.querySelector('[onclick*="openReconnect"]'); if (rc && rc.nextSibling) row.insertBefore(btn, rc.nextSibling); else row.appendChild(btn); }
    }
  };
})();
