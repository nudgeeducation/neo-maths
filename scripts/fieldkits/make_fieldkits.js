// Builds docs/assets/fieldkits/<unit-id>.js from each unit's diagnostic expedition, so the
// tools a learner meets in the expedition are also available inside the unit's lessons.
// Run (needs jsdom, e.g. from ~/.neo-maths-tools): node scripts/fieldkits/make_fieldkits.js
const fs = require('fs'), path = require('path');
let JSDOM; try { ({ JSDOM } = require('jsdom')); } catch (e) { ({ JSDOM } = require(path.join(process.env.HOME, '.neo-maths-tools/node_modules/jsdom'))); }
const ROOT = path.join(__dirname, '..', '..');
const PROTO = path.join(ROOT, 'vault/99_Working/Assessment_Prototypes');
// One line per unit that has an expedition: the unit id in docs/data/curriculum.json, the prototype, and its name.
const KITS = [
  { unit: 'inequalities', file: 'NEO_Maths_Y9_Inequalities_Walled_Garden_v0.3.html', expedition: 'The Walled Garden' },
  { unit: 'formulae-rearranging', file: 'NEO_Maths_Y9_Formulae_Inventors_Workshop_v0.1.html', expedition: 'The Inventor’s Workshop' },
  { unit: 'number-systems', file: 'NEO_Maths_Y10_Number_Systems_Observatory_v0.3.html', expedition: 'The Observatory' },
  { unit: 'algebraic-expressions', file: 'NEO_Maths_Y10_Algebraic_Expressions_Lighthouse_v0.1.html', expedition: 'The Lighthouse' }
];
const outDir = path.join(ROOT, 'docs/assets/fieldkits');
fs.mkdirSync(outDir, { recursive: true });
for (const k of KITS) {
  const html = fs.readFileSync(path.join(PROTO, k.file), 'utf8');
  const dom = new JSDOM(html, { runScripts: 'dangerously', url: 'https://kit.test/' });
  const w = dom.window;
  const tools = w.eval('KIT.map(function(t,i){return {title:t.title, icon:t.icon, body:t.body(), room:ROOMS[i].name, lesson:ROOMS[i].lesson};})');
  const data = { unit: k.unit, expedition: k.expedition, tools: JSON.parse(JSON.stringify(tools)) };
  fs.writeFileSync(path.join(outDir, k.unit + '.js'), '/* Generated by scripts/fieldkits/make_fieldkits.js from ' + k.file + ' — do not edit by hand. */\nwindow.NEO_FIELDKIT=' + JSON.stringify(data) + ';\n');
  console.log('wrote', k.unit, tools.length, 'tools');
}
